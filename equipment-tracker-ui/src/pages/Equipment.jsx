import { useCallback, useEffect, useState } from "react";
import {
    createEquipment,
    extractErrorMessage,
    getEquipment,
} from "../services/api";

const CATEGORIES = ["LAPTOP", "DESKTOP", "PHONE", "PERIPHERAL", "OTHER"];

const EMPTY_FORM = { name: "", category: CATEGORIES[0], serialNumber: "" };

const STATUS_COLORS = {
    AVAILABLE: { background: "#dcfce7", color: "#166534" },
    CHECKED_OUT: { background: "#fee2e2", color: "#991b1b" },
    MAINTENANCE: { background: "#fef9c3", color: "#854d0e" },
};

const styles = {
    page: { maxWidth: "900px", margin: "0 auto", padding: "2rem" },
    card: {
        border: "1px solid #e5e7eb",
        borderRadius: "8px",
        padding: "1rem 1.25rem",
        background: "#fff",
        marginBottom: "1.5rem",
    },
    formGrid: {
        display: "grid",
        gridTemplateColumns: "repeat(auto-fit, minmax(180px, 1fr))",
        gap: "0.75rem",
        alignItems: "end",
    },
    label: {
        display: "flex",
        flexDirection: "column",
        gap: "4px",
        fontSize: "0.875rem",
        fontWeight: 500,
        color: "#374151",
    },
    input: {
        padding: "0.5rem",
        border: "1px solid #d1d5db",
        borderRadius: "6px",
        fontSize: "0.95rem",
    },
    button: {
        padding: "0.55rem 1rem",
        border: "none",
        borderRadius: "6px",
        background: "#2563eb",
        color: "#fff",
        fontWeight: 600,
        cursor: "pointer",
    },
    table: { width: "100%", borderCollapse: "collapse", background: "#fff" },
    th: {
        textAlign: "left",
        padding: "0.65rem 0.75rem",
        borderBottom: "2px solid #e5e7eb",
        fontSize: "0.8rem",
        textTransform: "uppercase",
        color: "#6b7280",
    },
    td: { padding: "0.65rem 0.75rem", borderBottom: "1px solid #f3f4f6" },
    tag: { fontFamily: "monospace", fontWeight: 600 },
    muted: { color: "#9ca3af" },
    badge: {
        padding: "2px 10px",
        borderRadius: "999px",
        fontSize: "0.75rem",
        fontWeight: 600,
    },
    error: {
        background: "#fee2e2",
        color: "#991b1b",
        padding: "0.75rem 1rem",
        borderRadius: "6px",
        marginBottom: "1rem",
    },
    success: {
        background: "#dcfce7",
        color: "#166534",
        padding: "0.75rem 1rem",
        borderRadius: "6px",
        marginBottom: "1rem",
    },
};

export default function Equipment() {
    const [equipment, setEquipment] = useState([]);
    const [form, setForm] = useState(EMPTY_FORM);
    const [loading, setLoading] = useState(true);
    const [submitting, setSubmitting] = useState(false);
    const [error, setError] = useState(null);
    const [success, setSuccess] = useState(null);

    const loadEquipment = useCallback(async () => {
        try {
            setEquipment(await getEquipment());
        } catch (err) {
            setError(extractErrorMessage(err));
        }
    }, []);

    useEffect(() => {
        const init = async () => {
            await loadEquipment();
            setLoading(false);
        };
        init();
    }, [loadEquipment]);

    const handleChange = (e) => {
        const { name, value } = e.target;
        setForm((prev) => ({ ...prev, [name]: value }));
    };

    const handleSubmit = async (e) => {
        e.preventDefault();
        setSubmitting(true);
        setError(null);
        setSuccess(null);
        try {
            // Serial number is optional: send null rather than an empty string.
            // The asset tag is generated by the backend.
            const created = await createEquipment({
                ...form,
                serialNumber: form.serialNumber.trim() || null,
            });
            setSuccess(`Equipment "${created.name}" added with asset tag ${created.assetTag}.`);
            setForm(EMPTY_FORM);
            await loadEquipment();
        } catch (err) {
            setError(extractErrorMessage(err));
        } finally {
            setSubmitting(false);
        }
    };

    return (
        <div style={styles.page}>
            <h1>Equipment</h1>

            <form style={styles.card} onSubmit={handleSubmit}>
                <h3 style={{ marginTop: 0 }}>Add equipment</h3>
                <div style={styles.formGrid}>
                    <label style={styles.label}>
                        Name
                        <input
                            style={styles.input}
                            name="name"
                            value={form.name}
                            onChange={handleChange}
                            required
                        />
                    </label>
                    <label style={styles.label}>
                        Category
                        <select
                            style={styles.input}
                            name="category"
                            value={form.category}
                            onChange={handleChange}
                        >
                            {CATEGORIES.map((category) => (
                                <option key={category} value={category}>
                                    {category}
                                </option>
                            ))}
                        </select>
                    </label>
                    <label style={styles.label}>
                        Serial number
                        <input
                            style={styles.input}
                            name="serialNumber"
                            value={form.serialNumber}
                            onChange={handleChange}
                            placeholder="Optional"
                        />
                    </label>
                    <button
                        type="submit"
                        style={{ ...styles.button, opacity: submitting ? 0.6 : 1 }}
                        disabled={submitting}
                    >
                        {submitting ? "Saving..." : "Add equipment"}
                    </button>
                </div>
            </form>

            {error && <div style={styles.error}>{error}</div>}
            {success && <div style={styles.success}>{success}</div>}
            {loading && <p>Loading equipment...</p>}
            {!loading && equipment.length === 0 && !error && <p>No equipment yet.</p>}

            {equipment.length > 0 && (
                <table style={styles.table}>
                    <thead>
                    <tr>
                        <th style={styles.th}>ID</th>
                        <th style={styles.th}>Asset tag</th>
                        <th style={styles.th}>Name</th>
                        <th style={styles.th}>Category</th>
                        <th style={styles.th}>Serial number</th>
                        <th style={styles.th}>Status</th>
                    </tr>
                    </thead>
                    <tbody>
                    {equipment.map((item) => (
                        <tr key={item.id}>
                            <td style={styles.td}>{item.id}</td>
                            <td style={styles.td}>
                                {item.assetTag ? (
                                    <span style={styles.tag}>{item.assetTag}</span>
                                ) : (
                                    <span style={styles.muted}>—</span>
                                )}
                            </td>
                            <td style={styles.td}>{item.name}</td>
                            <td style={styles.td}>{item.category}</td>
                            <td style={styles.td}>
                                {item.serialNumber ?? <span style={styles.muted}>—</span>}
                            </td>
                            <td style={styles.td}>
                  <span style={{ ...styles.badge, ...STATUS_COLORS[item.status] }}>
                    {item.status.replace("_", " ")}
                  </span>
                            </td>
                        </tr>
                    ))}
                    </tbody>
                </table>
            )}
        </div>
    );
}